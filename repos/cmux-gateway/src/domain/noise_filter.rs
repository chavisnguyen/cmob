/// All 19 harness XML tag names injected into user-role turns by Claude / agent harnesses.
/// Source: `ref/orca/src/shared/harness-injected-user-turns.ts:5-25`
pub const KNOWN_HARNESS_TAG_NAMES: &[&str] = &[
    "agent-message",
    "bash-input",
    "bash-stderr",
    "bash-stdout",
    "command-args",
    "command-message",
    "command-name",
    "cross-session-message",
    "fork-boilerplate",
    "local-command-caveat",
    "local-command-stderr",
    "local-command-stdout",
    "mcp-polling-update",
    "mcp-resource-update",
    "system-reminder",
    "task-notification",
    "teammate-message",
    "user-memory-input",
    "user-prompt-submit-hook",
];

pub const COMPACT_CONTINUATION_PREFIX: &str =
    "this session is being continued from a previous conversation";

/// All 7 prose prefixes injected by agent harnesses as user-role messages.
/// Source: `ref/orca/src/shared/harness-injected-user-turns.ts:28-37`
pub const HARNESS_INJECTED_TURN_PREFIXES: &[&str] = &[
    "<channel source=",
    "[request interrupted",
    "a message arrived from ",
    "another claude session sent a message",
    "no response requested.",
    "caveat: the messages below were generated by the user while running local commands",
    COMPACT_CONTINUATION_PREFIX,
];

const HARNESS_CLASSIFY_HEAD_LIMIT: usize = 256;
const HARNESS_CLASSIFY_LEADING_WS_LIMIT: usize = 64;

fn is_ascii_harness_ws(b: u8) -> bool {
    matches!(b, b' ' | b'\t' | b'\n' | b'\r' | 0x0c)
}

fn normalized_harness_turn_head(text: &str) -> String {
    let bytes = text.as_bytes();
    let ws_scan_end = bytes.len().min(HARNESS_CLASSIFY_LEADING_WS_LIMIT);
    let mut start = 0usize;
    while start < ws_scan_end && is_ascii_harness_ws(bytes[start]) {
        start += 1;
    }
    if start >= bytes.len() {
        return String::new();
    }
    let rest = &text[start..];
    let head: String = rest.chars().take(HARNESS_CLASSIFY_HEAD_LIMIT).collect();
    head.to_lowercase()
}

fn extract_leading_tag_name(normalized: &str) -> Option<&str> {
    let after_lt = normalized.strip_prefix('<')?;
    let mut chars = after_lt.char_indices();
    let (_, first) = chars.next()?;
    if !first.is_ascii_lowercase() {
        return None;
    }
    let mut end = first.len_utf8();
    for (idx, ch) in chars {
        if ch.is_ascii_lowercase() || ch.is_ascii_digit() || ch == '-' {
            end = idx + ch.len_utf8();
        } else if ch == '>' || ch.is_whitespace() {
            return Some(&after_lt[..end]);
        } else {
            return None;
        }
    }
    Some(&after_lt[..end])
}

/// Port of Orca's `isKnownHarnessInjectedUserTurnText`.
/// Matches only observed harness tags and prose prefixes on trimmed, lowercased head text.
pub fn is_known_harness_injected_user_turn_text(text: &str) -> bool {
    let normalized = normalized_harness_turn_head(text);
    if normalized.is_empty() {
        return false;
    }
    if let Some(tag_name) = extract_leading_tag_name(&normalized)
        && KNOWN_HARNESS_TAG_NAMES.contains(&tag_name)
    {
        return true;
    }
    HARNESS_INJECTED_TURN_PREFIXES
        .iter()
        .any(|prefix| normalized.starts_with(prefix))
}

/// True only for the post-compaction continuation summary prompt.
pub fn is_compact_continuation_user_turn_text(text: &str) -> bool {
    normalized_harness_turn_head(text).starts_with(COMPACT_CONTINUATION_PREFIX)
}

/// True when the user-role text is a harness interruption marker (`[Request interrupted ...]`).
pub fn is_interrupted_user_turn_text(text: &str) -> bool {
    normalized_harness_turn_head(text).starts_with("[request interrupted")
}

/// Unwraps Claude's `<bash-input>cmd</bash-input>` into `!cmd`.
/// Source: `ref/orca/src/shared/claude-bash-input.ts:6-9`
pub fn unwrap_claude_bash_input(text: &str) -> Option<String> {
    let trimmed = text.trim();
    let inner = trimmed
        .strip_prefix("<bash-input>")?
        .strip_suffix("</bash-input>")?;
    if inner.contains("<bash-input>") {
        return None;
    }
    Some(format!("!{inner}"))
}

/// Unwraps Claude's `<pasted_content ...>body</pasted_content>` into `body`.
/// Supports both Orca's newline-delimited form and inline `<pasted_content ...>body</pasted_content>`.
/// Source: `ref/orca/src/shared/claude-pasted-content.ts:4-23`
pub fn unwrap_claude_pasted_content(text: &str) -> String {
    let trimmed = text.trim();
    let Some(after_open_prefix) = trimmed.strip_prefix("<pasted_content") else {
        return text.to_string();
    };
    let (id_opt, body_with_close) = if let Some(rest) = after_open_prefix.strip_prefix('>') {
        (None, rest)
    } else if let Some(rest) = after_open_prefix.strip_prefix(" ") {
        let Some(gt_idx) = rest.find('>') else {
            return text.to_string();
        };
        let attr_str = rest[..gt_idx].trim();
        let parsed_id = attr_str
            .strip_prefix("id=\"")
            .and_then(|s| s.strip_suffix('"'))
            .filter(|id| {
                !id.is_empty()
                    && id.len() <= 64
                    && !id.contains(['"', '<', '>', '\r', '\n'])
            });
        (parsed_id, &rest[gt_idx + 1..])
    } else {
        return text.to_string();
    };

    let attributed_close = id_opt.map(|id| format!("</pasted_content id=\"{id}\">"));
    let body = if let Some(ref close_tag) = attributed_close {
        if let Some(b) = body_with_close.strip_suffix(close_tag.as_str()) {
            b
        } else if let Some(b) = body_with_close.strip_suffix("</pasted_content>") {
            b
        } else {
            return text.to_string();
        }
    } else if let Some(b) = body_with_close.strip_suffix("</pasted_content>") {
        b
    } else {
        return text.to_string();
    };

    let ambiguous = match id_opt {
        Some(id) => {
            let open_same = format!("<pasted_content id=\"{id}\">");
            let close_same = format!("</pasted_content id=\"{id}\">");
            body.contains(&open_same) || body.contains(&close_same)
        }
        None => body.contains("<pasted_content") || body.contains("</pasted_content"),
    };
    if ambiguous {
        return text.to_string();
    }

    let stripped_lead = body
        .strip_prefix("\r\n")
        .or_else(|| body.strip_prefix('\n'))
        .unwrap_or(body);
    let stripped_both = stripped_lead
        .strip_suffix("\r\n")
        .or_else(|| stripped_lead.strip_suffix('\n'))
        .unwrap_or(stripped_lead);
    stripped_both.to_string()
}

fn extract_xml_tag_body<'a>(src: &'a str, tag: &str) -> Option<&'a str> {
    let open = format!("<{tag}>");
    let close = format!("</{tag}>");
    let start = src.find(&open)? + open.len();
    let end = src[start..].find(&close)?;
    Some(&src[start..start + end])
}

/// Unwraps Claude's slash-command envelope (`<command-name>/skill</command-name>` +
/// optional `<command-args>args</command-args>`, even alongside `<command-message>`)
/// into `"/skill args"` or `"/skill"`.
pub fn unwrap_claude_slash_command(text: &str) -> Option<String> {
    let normalized = normalized_harness_turn_head(text);
    let lead_tag = extract_leading_tag_name(&normalized)?;
    if !matches!(
        lead_tag,
        "command-name" | "command-message" | "command-args" | "local-command-caveat"
    ) {
        return None;
    }
    let raw_cmd = extract_xml_tag_body(text, "command-name")?.trim();
    if raw_cmd.is_empty() {
        return None;
    }
    let cmd = if raw_cmd.starts_with('/') {
        raw_cmd.to_string()
    } else {
        format!("/{raw_cmd}")
    };
    let args = extract_xml_tag_body(text, "command-args")
        .map(str::trim)
        .unwrap_or("");
    if args.is_empty() {
        Some(cmd)
    } else {
        Some(format!("{cmd} {args}"))
    }
}

/// Normalizes a single Claude user text block:
/// 1. Unwraps `<pasted_content>`
/// 2. Unwraps `<bash-input>` -> `!cmd`
/// 3. Unwraps `<command-name>` -> `/skill args`
/// 4. Drops any remaining harness-injected text (`KNOWN_HARNESS_TAG_NAMES` + 7 prose prefixes).
pub fn normalize_claude_user_block_text(text: &str) -> Option<String> {
    if let Some(bash) = unwrap_claude_bash_input(text) {
        return (!bash.trim().is_empty()).then_some(bash);
    }
    if let Some(slash) = unwrap_claude_slash_command(text) {
        return (!slash.trim().is_empty()).then_some(slash);
    }
    let unpasted = unwrap_claude_pasted_content(text);
    if unpasted != text {
        return (!unpasted.trim().is_empty()).then_some(unpasted);
    }
    if is_known_harness_injected_user_turn_text(text) {
        return None;
    }
    (!text.trim().is_empty()).then(|| text.to_string())
}

fn strip_all_additional_metadata(input: &str) -> String {
    const OPEN: &str = "<ADDITIONAL_METADATA>";
    const CLOSE: &str = "</ADDITIONAL_METADATA>";
    let mut out = input.to_string();
    while let Some(start) = out.find(OPEN) {
        if let Some(rel_end) = out[start + OPEN.len()..].find(CLOSE) {
            let end = start + OPEN.len() + rel_end + CLOSE.len();
            out.replace_range(start..end, "");
        } else {
            out.truncate(start);
            break;
        }
    }
    out
}

/// Extracts user prompt text, stripping Antigravity `<USER_REQUEST>` (even if `</USER_REQUEST>`
/// is truncated/missing), `<user_prompt>`, and loop-stripping all `<ADDITIONAL_METADATA>` blocks.
/// Source: `ref/orca/src/main/ai-vault/scanners/antigravity/session-scanner-antigravity-parser.ts:135-146`
pub fn clean_user_prompt(text: &str) -> String {
    let without_meta = strip_all_additional_metadata(text);
    let s = without_meta.trim();
    if let Some(start) = s.find("<USER_REQUEST>") {
        let after_start = &s[start + "<USER_REQUEST>".len()..];
        let body = match after_start.find("</USER_REQUEST>") {
            Some(end) => &after_start[..end],
            None => after_start,
        };
        return strip_all_additional_metadata(body).trim().to_string();
    }
    if let Some(start) = s.find("<user_prompt>") {
        let after_start = &s[start + "<user_prompt>".len()..];
        let body = match after_start.find("</user_prompt>") {
            Some(end) => &after_start[..end],
            None => after_start,
        };
        return strip_all_additional_metadata(body).trim().to_string();
    }
    s.to_string()
}

/// True when a Codex content block is an injected `<skill>` expansion.
/// Source: `ref/orca/src/main/native-chat/transcript-line-decoders-codex.ts:134-136`
pub fn is_codex_skill_block(text: &str) -> bool {
    let trimmed = text.trim_start();
    trimmed
        .get(..7)
        .is_some_and(|head| head.eq_ignore_ascii_case("<skill>"))
}

/// Strips all `<skill>...</skill>` (case-insensitive) blocks from a Codex user prompt string.
pub fn strip_codex_skill_blocks(text: &str) -> String {
    let mut out = text.to_string();
    loop {
        let lower = out.to_ascii_lowercase();
        let Some(start) = lower.find("<skill>") else {
            break;
        };
        if let Some(rel_end) = lower[start + 7..].find("</skill>") {
            let end = start + 7 + rel_end + "</skill>".len();
            out.replace_range(start..end, "");
        } else {
            out.truncate(start);
            break;
        }
    }
    out.trim().to_string()
}

/// Howard Hinnant civil-to-days algorithm (days since 1970-01-01).
fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = y - if m <= 2 { 1 } else { 0 };
    let era = y.div_euclid(400);
    let yoe = y.rem_euclid(400);
    let doy = (153 * (m + if m > 2 { -3 } else { 9 }) + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// Parses an ISO-8601 / RFC3339 timestamp (`YYYY-MM-DDTHH:MM:SS[.fff...](Z|+HH:MM|-HH:MM|+HHMM|-HHMM)`)
/// into Unix seconds as `f64`.
pub fn parse_rfc3339_secs(s: &str) -> Option<f64> {
    let s = s.trim();
    let (date_part, rest) = s.split_once(['T', 't'])?;
    let mut d_parts = date_part.split('-');
    let year: i64 = d_parts.next()?.parse().ok()?;
    let month: u32 = d_parts.next()?.parse().ok()?;
    let day: u32 = d_parts.next()?.parse().ok()?;
    if d_parts.next().is_some() || !(1..=12).contains(&month) || !(1..=31).contains(&day) {
        return None;
    }

    let (time_str, tz_offset_secs): (&str, i64) = if let Some(stripped) = rest.strip_suffix(['Z', 'z']) {
        (stripped, 0)
    } else {
        let idx = rest.rfind(['+', '-'])?;
        let (t, off) = rest.split_at(idx);
        let sign: i64 = if off.starts_with('-') { -1 } else { 1 };
        let off = &off[1..];
        let (oh, om) = if let Some((h, m)) = off.split_once(':') {
            (h.parse::<i64>().ok()?, m.parse::<i64>().ok()?)
        } else if off.len() == 4 {
            (off[..2].parse::<i64>().ok()?, off[2..].parse::<i64>().ok()?)
        } else {
            return None;
        };
        if !(0..=23).contains(&oh) || !(0..=59).contains(&om) {
            return None;
        }
        (t, sign * (oh * 3600 + om * 60))
    };

    let (hms, frac_secs): (&str, f64) = match time_str.split_once('.') {
        Some((hms, frac)) => {
            if frac.is_empty() || !frac.chars().all(|c| c.is_ascii_digit()) {
                return None;
            }
            let digits: String = frac.chars().take(9).collect();
            let frac_val = format!("0.{digits}").parse::<f64>().ok()?;
            (hms, frac_val)
        }
        None => (time_str, 0.0),
    };

    let mut t_parts = hms.split(':');
    let hour: i64 = t_parts.next()?.parse().ok()?;
    let min: i64 = t_parts.next()?.parse().ok()?;
    let sec: i64 = t_parts.next()?.parse().ok()?;
    if t_parts.next().is_some()
        || !(0..=23).contains(&hour)
        || !(0..=59).contains(&min)
        || !(0..=60).contains(&sec)
    {
        return None;
    }

    let days = days_from_civil(year, month as i64, day as i64);
    let secs = days * 86_400 + hour * 3600 + min * 60 + sec - tz_offset_secs;
    if secs < 0 {
        return None;
    }
    Some(secs as f64 + frac_secs)
}

/// Parses an ISO-8601 / RFC3339 timestamp into Unix milliseconds (`u64`), supporting both `Z` and `[+-]HH:MM` offsets.
pub fn parse_rfc3339_ms(s: &str) -> Option<u64> {
    let secs = parse_rfc3339_secs(s)?;
    Some((secs * 1000.0).round() as u64)
}

/// Extracts Unix timestamp in ms from a JSON record's `timestamp` or `created_at` field.
pub fn record_timestamp_ms(val: &serde_json::Value) -> Option<u64> {
    for key in ["timestamp", "created_at", "time_created"] {
        let Some(v) = val.get(key) else { continue };
        if let Some(s) = v.as_str() {
            if let Some(ms) = parse_rfc3339_ms(s) {
                return Some(ms);
            }
        } else if let Some(n) = v.as_u64() {
            return Some(if n > 10_000_000_000 { n } else { n * 1000 });
        } else if let Some(f) = v.as_f64()
            && f.is_finite()
            && f >= 0.0
        {
            return Some(if f > 10_000_000_000.0 {
                f as u64
            } else {
                (f * 1000.0) as u64
            });
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_all_19_harness_tags_and_7_prefixes() {
        for tag in KNOWN_HARNESS_TAG_NAMES {
            assert!(
                is_known_harness_injected_user_turn_text(&format!("<{tag}>payload</{tag}>")),
                "tag {tag} must match"
            );
            assert!(
                is_known_harness_injected_user_turn_text(&format!("  \n <{tag} attr=\"1\">x")),
                "attributed tag {tag} must match"
            );
        }
        for prefix in HARNESS_INJECTED_TURN_PREFIXES {
            assert!(
                is_known_harness_injected_user_turn_text(&format!("  {prefix} extra")),
                "prefix {prefix} must match"
            );
        }
        // Legitimate user XML / prose is never misclassified as harness noise.
        assert!(!is_known_harness_injected_user_turn_text("<channel><item>rss</item></channel>"));
        assert!(!is_known_harness_injected_user_turn_text("<div class=\"app\">hello</div>"));
        assert!(!is_known_harness_injected_user_turn_text("fix the flaky test"));
    }

    #[test]
    fn unwraps_claude_bash_pasted_and_slash_commands() {
        assert_eq!(
            normalize_claude_user_block_text("<bash-input>git status -sb</bash-input>").as_deref(),
            Some("!git status -sb")
        );
        assert_eq!(
            normalize_claude_user_block_text("<pasted_content id=\"abc\">\nline 1\nline 2\n</pasted_content id=\"abc\">").as_deref(),
            Some("line 1\nline 2")
        );
        assert_eq!(
            normalize_claude_user_block_text("<pasted_content>inline body</pasted_content>").as_deref(),
            Some("inline body")
        );
        assert_eq!(
            normalize_claude_user_block_text(
                "<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>123</command-args>"
            )
            .as_deref(),
            Some("/review 123")
        );
        assert_eq!(
            normalize_claude_user_block_text("<command-name>/compact</command-name><command-args></command-args>").as_deref(),
            Some("/compact")
        );
        assert!(normalize_claude_user_block_text("<local-command-caveat>ignore</local-command-caveat>").is_none());
        assert!(normalize_claude_user_block_text("<system-reminder>secret</system-reminder>").is_none());
    }

    #[test]
    fn cleans_antigravity_truncated_user_request_and_multiple_metadata_blocks() {
        assert_eq!(
            clean_user_prompt("<USER_REQUEST>ship clean arch"),
            "ship clean arch"
        );
        assert_eq!(
            clean_user_prompt(
                "<USER_REQUEST>deploy</USER_REQUEST><ADDITIONAL_METADATA>one</ADDITIONAL_METADATA><ADDITIONAL_METADATA>two</ADDITIONAL_METADATA>"
            ),
            "deploy"
        );
        assert_eq!(
            clean_user_prompt("raw prompt <ADDITIONAL_METADATA>m1</ADDITIONAL_METADATA> <ADDITIONAL_METADATA>m2</ADDITIONAL_METADATA>"),
            "raw prompt"
        );
    }

    #[test]
    fn strips_codex_skill_blocks() {
        assert!(is_codex_skill_block("  <skill>\n# SKILL\n</skill>"));
        assert_eq!(
            strip_codex_skill_blocks("<skill>internal skill guide</skill>\n\nAudit the repo"),
            "Audit the repo"
        );
    }

    #[test]
    fn parses_rfc3339_utc_and_offsets() {
        assert_eq!(parse_rfc3339_ms("1970-01-01T00:01:00Z"), Some(60_000));
        assert_eq!(parse_rfc3339_ms("2026-12-01T19:00:47Z"), Some(1_796_151_647_000));
        assert_eq!(parse_rfc3339_ms("2026-12-02T02:00:47+07:00"), Some(1_796_151_647_000));
        assert_eq!(parse_rfc3339_ms("2026-12-01T14:00:47.250-05:00"), Some(1_796_151_647_250));
        assert!(parse_rfc3339_secs("2026-11-12 10:47:18").is_none());
    }
}
